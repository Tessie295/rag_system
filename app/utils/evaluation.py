@time_function
async def evaluate_answer(query: str, answer: str, source_documents: List[str]) -> QueryEvaluation:
    """
    Evaluate the quality of an answer based on the source documents and query.
    
    Args:
        query: The user's question
        answer: The generated answer
        source_documents: List of text from the source documents used
    
    Returns:
        QueryEvaluation object with scores and feedback
    """
    # Start timer for evaluation
    start_time = time.time()
    
    # Combine evaluation methods for a robust assessment
    correctness_score = await evaluate_factual_correctness(answer, source_documents)
    relevance_score = evaluate_relevance(query, answer)
    completeness_score = evaluate_completeness(query, answer, source_documents)
    
    # Calculate overall score (weighted average)
    overall_score = (0.4 * correctness_score + 0.4 * relevance_score + 0.2 * completeness_score)
    
    # Generate feedback based on scores
    feedback = generate_evaluation_feedback(
        correctness_score, relevance_score, completeness_score, overall_score
    )
    
    # Log evaluation time
    evaluation_time = time.time() - start_time
    logger.debug(f"Answer evaluation completed in {evaluation_time:.4f}s")
    
    return QueryEvaluation(
        correctness_score=correctness_score,
        relevance_score=relevance_score,
        completeness_score=completeness_score,
        overall_score=overall_score,
        feedback=feedback
    )

async def evaluate_factual_correctness(answer: str, source_documents: List[str]) -> float:
    """
    Evaluate the factual correctness of the answer against the source documents.
    Uses LLM-based evaluation when available, falls back to lexical similarity.
    """
    # For efficiency, first try a simpler lexical approach
    if not settings.USE_LLM_FOR_EVALUATION:
        return evaluate_lexical_correctness(answer, source_documents)
    
    try:
        # Use an LLM to evaluate factual correctness
        evaluation_llm = ChatOpenAI(
            model_name=settings.EVALUATION_MODEL,
            openai_api_key=settings.OPENAI_API_KEY,
            temperature=0.0
        )
        
        # Create a prompt for the evaluation
        evaluation_template = ChatPromptTemplate.from_template(
            """You are an AI assistant evaluating the factual correctness of an answer based on source documents.
            
            Source documents:
            {source_documents}
            
            Answer to evaluate:
            {answer}
            
            Evaluate the factual correctness of the answer based ONLY on the provided source documents.
            Assign a score from 0.0 to 1.0, where:
            - 1.0: The answer is completely factually correct and all claims are supported by the sources.
            - 0.7-0.9: The answer is mostly correct with minor inaccuracies or assumptions.
            - 0.4-0.6: The answer has some correct information but also contains significant inaccuracies.
            - 0.0-0.3: The answer is mostly incorrect or makes claims not supported by the sources.
            
            Output only a single decimal number between 0.0 and 1.0 representing your evaluation score.
            """
        )
        
        evaluation_chain = LLMChain(llm=evaluation_llm, prompt=evaluation_template)
        
        # Combine source documents with length limit
        combined_sources = "\n\n".join(source_documents)
        if len(combined_sources) > 12000:  # Limit context size
            combined_sources = combined_sources[:12000] + "..."
        
        # Run the evaluation with a timeout
        try:
            result = await asyncio.wait_for(
                evaluation_chain.arun(
                    source_documents=combined_sources, 
                    answer=answer
                ),
                timeout=3.0  # Timeout after 3 seconds
            )
            
            # Extract the score
            try:
                score = float(result.strip())
                # Ensure the score is in the valid range
                score = max(0.0, min(1.0, score))
                return score
            except ValueError:
                logger.warning("Failed to parse LLM evaluation score, falling back to lexical evaluation")
                return evaluate_lexical_correctness(answer, source_documents)
                
        except asyncio.TimeoutError:
            logger.warning("LLM evaluation timed out, falling back to lexical evaluation")
            return evaluate_lexical_correctness(answer, source_documents)
            
    except Exception as e:
        logger.error(f"Error in LLM-based factual evaluation: {e}")
        # Fall back to lexical similarity if LLM evaluation fails
        return evaluate_lexical_correctness(answer, source_documents)
    
def evaluate_lexical_correctness(answer: str, source_documents: List[str]) -> float:
    """
    Evaluate factual correctness based on lexical overlap with source documents.
    """
    if not source_documents:
        return 0.5  # Neutral score if no sources
    
    # Create TF-IDF vectors
    vectorizer = TfidfVectorizer(stop_words='english')
    
    # Combine all source documents
    combined_sources = " ".join(source_documents)
    
    # Handle empty strings
    if not answer.strip() or not combined_sources.strip():
        return 0.5
    
    try:
        # Create the document matrix
        tfidf_matrix = vectorizer.fit_transform([answer, combined_sources])
        
        # Calculate similarity
        similarity = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
        
        # Normalize to a reasonable score (similarity tends to be lower than human judgment)
        normalized_score = min(1.0, similarity * 1.5)
        return normalized_score
    
    except Exception as e:
        logger.error(f"Error in lexical correctness evaluation: {e}")
        return 0.5  # Neutral score on error

def evaluate_relevance(query: str, answer: str) -> float:
    """
    Evaluate how relevant the answer is to the query.
    """
    # Create TF-IDF vectors
    vectorizer = TfidfVectorizer(stop_words='english')
    
    # Handle empty strings
    if not query.strip() or not answer.strip():
        return 0.5
    
    try:
        # Create the document matrix
        tfidf_matrix = vectorizer.fit_transform([query, answer])
        
        # Calculate similarity
        similarity = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
        
        # Adjust the score based on answer length
        # Very short answers might be relevant but incomplete
        length_factor = min(1.0, len(answer) / 200)
        
        # Combine similarity with length factor
        relevance_score = similarity * (0.7 + (0.3 * length_factor))
        
        return min(1.0, relevance_score * 1.2)  # Boost score slightly, capped at 1.0
    
    except Exception as e:
        logger.error(f"Error in relevance evaluation: {e}")
        return 0.5  # Neutral score on error

def evaluate_completeness(query: str, answer: str, source_documents: List[str]) -> float:
    """
    Evaluate how completely the answer addresses the query based on available information.
    """
    if not source_documents:
        return 0.5  # Neutral score if no sources
    
    # Extract potential key terms from the query
    query_terms = set(query.lower().split())
    stop_words = {'the', 'a', 'an', 'and', 'or', 'but', 'is', 'are', 'was', 'were', 
                  'in', 'on', 'at', 'to', 'for', 'with', 'about', 'how', 'what', 
                  'why', 'when', 'where', 'who', 'which', 'can', 'do', 'does', 'i', 
                  'you', 'we', 'they', 'it', 'of', 'from'}
    query_terms = query_terms - stop_words
    
    # Count terms in the answer
    answer_terms = set(answer.lower().split()) - stop_words
    
    # Check if key terms from the query appear in the answer
    term_coverage = sum(1 for term in query_terms if any(term in ans_term for ans_term in answer_terms))
    term_coverage_score = term_coverage / max(1, len(query_terms))
    
    # Consider answer length relative to source documents
    avg_source_length = sum(len(doc.split()) for doc in source_documents) / len(source_documents)
    answer_length = len(answer.split())
    
    # Too short answers might be incomplete
    length_ratio = min(1.0, answer_length / (avg_source_length * 0.3))
    
    # Combine metrics
    completeness_score = (0.7 * term_coverage_score) + (0.3 * length_ratio)
    
    return min(1.0, completeness_score)

def evaluate_bleu_score(answer: str, references: List[str]) -> float:
    """
    Calculate BLEU score for the answer against reference texts.
    """
    try:
        answer_tokens = word_tokenize(answer.lower())
        reference_tokens = [word_tokenize(ref.lower()) for ref in references if ref.strip()]
        
        if not reference_tokens:
            return 0.5  # Neutral score if no valid references
        
        # Calculate BLEU score with smoothing
        bleu_score = sentence_bleu(reference_tokens, answer_tokens, smoothing_function=None)
        
        # BLEU scores are often very low, normalize for usefulness
        normalized_bleu = min(1.0, bleu_score * 5.0)
        return normalized_bleu
        
    except Exception as e:
        logger.error(f"Error calculating BLEU score: {e}")
        return 0.5  # Neutral score on error

def generate_evaluation_feedback(correctness: float, relevance: float, 
                               completeness: float, overall: float) -> str:
    """Generate human-readable feedback based on evaluation scores."""
    feedback = []
    
    if overall >= 0.8:
        feedback.append("The response is of high quality.")
    elif overall >= 0.6:
        feedback.append("The response is adequate but could be improved.")
    else:
        feedback.append("The response needs significant improvement.")
    
    # Add specific feedback based on individual metrics
    if correctness < 0.6:
        feedback.append("Factual accuracy could be improved.")
    
    if relevance < 0.6:
        feedback.append("The answer could be more directly relevant to the query.")
    
    if completeness < 0.6:
        feedback.append("The answer is not comprehensive enough.")
        
    return " ".join(feedback)

def evaluate_source_relevance(query: str, sources: List[str]) -> List[float]:
    """
    Evaluate the relevance of each source to the query.
    
    Args:
        query: The user's question
        sources: List of source document texts
        
    Returns:
        List of relevance scores for each source
    """
    if not sources:
        return []
    
    # Create TF-IDF vectors
    vectorizer = TfidfVectorizer(stop_words='english')
    
    try:
        # Create the document matrix
        docs = [query] + sources
        tfidf_matrix = vectorizer.fit_transform(docs)
        
        # Calculate query similarity with each source
        query_vector = tfidf_matrix[0:1]
        source_vectors = tfidf_matrix[1:]
        
        # Calculate pairwise similarities
        similarities = cosine_similarity(query_vector, source_vectors)[0]
        
        # Normalize scores to [0, 1]
        return [float(similarity) for similarity in similarities]
        
    except Exception as e:
        logger.error(f"Error in source relevance evaluation: {e}")
        return [0.5] * len(sources)  # Neutral scores on error

async def evaluate_recommendation_quality(query: str, recommendations: List[Dict[str, Any]], 
                                         user_history: List[str] = None) -> Dict[str, Any]:
    """
    Evaluate the quality of recommendations.
    
    Args:
        query: The user's current query
        recommendations: List of recommendation objects
        user_history: List of previous user queries
        
    Returns:
        Dictionary of evaluation metrics
    """
    if not recommendations:
        return {
            "relevance_score": 0.0,
            "diversity_score": 0.0,
            "overall_score": 0.0
        }
    
    # Evaluate relevance to the current query
    recommendation_texts = [rec.get("title", "") + " " + rec.get("explanation", "") 
                          for rec in recommendations]
    
    # Calculate relevance scores
    relevance_scores = []
    for text in recommendation_texts:
        try:
            vectorizer = TfidfVectorizer(stop_words='english')
            tfidf_matrix = vectorizer.fit_transform([query, text])
            similarity = cosine_similarity(tfidf_matrix[0:1], tfidf_matrix[1:2])[0][0]
            relevance_scores.append(similarity)
        except:
            relevance_scores.append(0.5)
    
    # Calculate average relevance
    avg_relevance = sum(relevance_scores) / len(relevance_scores) if relevance_scores else 0.0
    
    # Calculate diversity score (lower similarity between recommendations = higher diversity)
    diversity_score = 0.0
    if len(recommendation_texts) > 1:
        try:
            vectorizer = TfidfVectorizer(stop_words='english')
            tfidf_matrix = vectorizer.fit_transform(recommendation_texts)
            similarities = cosine_similarity(tfidf_matrix)
            
            # Calculate average off-diagonal similarity (excluding self-similarity)
            total_similarity = 0.0
            count = 0
            for i in range(len(similarities)):
                for j in range(len(similarities)):
                    if i != j:
                        total_similarity += similarities[i][j]
                        count += 1
            
            avg_similarity = total_similarity / count if count > 0 else 0.0
            diversity_score = 1.0 - avg_similarity  # Higher diversity = lower similarity
        except Exception as e:
            logger.error(f"Error calculating diversity score: {e}")
            diversity_score = 0.5
    else:
        diversity_score = 1.0  # Maximum diversity for a single recommendation
    
    # Combine into overall score (weighted average)
    overall_score = (0.7 * avg_relevance) + (0.3 * diversity_score)
    
    return {
        "relevance_score": avg_relevance,
        "diversity_score": diversity_score,
        "overall_score": overall_score,
        "individual_relevance": relevance_scores
    }